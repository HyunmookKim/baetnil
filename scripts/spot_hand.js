// 지도가 준 자리 이름이 그 권역과 맞나.
// ★ 막는 것은 **딴 도가 또렷이 적혀 있을 때뿐**이다.
//   자리 이름에 도 이름이 아예 안 적힌 때(「여수」 처럼 시 이름만)까지 막으면
//   멀쩡한 곳이 통째로 빠진다. 모르면 통과시키고 물가 검사에 맡긴다.
function 도가맞나(권역, 자리이름){
  const s = String(자리이름 || '');
  if(!s) return true;                                  // 이름을 안 줬다 — 못 가린다
  const 내말 = 도이름[권역];
  if(!내말) return true;                                // 모르는 권역은 안 막는다
  if(내말.some(w => s.indexOf(w) >= 0)) return true;     // 내 도가 적혀 있다
  const 남의도 = Object.keys(도이름).filter(k => k !== 권역)
      .some(k => 도이름[k].some(w => s.indexOf(w) >= 0));
  return !남의도;                                       // 딴 도가 적혀 있으면 딴 곳이다
}


